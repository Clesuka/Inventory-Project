// Helper to generate seed serial numbers
function generateSerials(
  itemId: string,
  prefix: string,
  count: number,
  warrantyMonths: number,
  startNum = 1001,
  purchaseDate = '2026-10-15T08:00:00.000Z'
): ItemSerialNumber[] {
  const serials: ItemSerialNumber[] = [];
  for (let i = 0; i < count; i++) {
    serials.push({
      id: `sn-${itemId}-${i + 1}`,
      itemId,
      serialNumber: `${prefix}-${startNum + i}`,
      status: 'IN_STOCK',
      warrantyMonths,
      purchaseDate,
    });
  }
  return serials;
}

